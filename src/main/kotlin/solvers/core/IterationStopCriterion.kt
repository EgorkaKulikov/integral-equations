package solvers.core

import solvers.core.SecondKindDefaults.DIVERGENCE_GROWTH_FACTOR

/**
 * ЕДИНЫЙ КРИТЕРИЙ ОСТАНОВА простых итераций уравнений II рода.
 *
 * Все три итерационные схемы проекта (`kulkarniQuasi` в [SecondKindSolverCore],
 * `combinedNystrom` у Фредгольма и у Вольтерры) строят последовательность итерантов
 * и меряют равномерную норму разности соседних на своём множестве контрольных точек.
 * Отличаются они ТОЛЬКО множеством точек; логика «что делать с полученным числом»
 * у них общая, и раньше она была выписана трижды. Дублирование того же сорта, что
 * уже устранено в [SecondKindDefaults]: правку одного экземпляра легко не перенести
 * в два других, и схемы, которые сравниваются между собой в характеризационных
 * тестах, молча разъедутся.
 *
 * Класс хранит состояние прогона и отвечает на единственный вопрос: прерывать ли цикл.
 *
 * ДВА условия выхода, порядок проверки существенен:
 *  1. сходимость `diff < tolerance` — проверяется ПЕРВОЙ, чтобы на границе поведение
 *     в точности совпадало с прежним (одноусловным) критерием;
 *  2. расходимость — критерий перестал быть конечным ЛИБО вырос относительно
 *     наименьшего достигнутого значения более чем в [DIVERGENCE_GROWTH_FACTOR] раз.
 *
 * @param tolerance требуемая величина критерия останова.
 */
internal class IterationStopCriterion(private val tolerance: Double) {

    /** Сходимость достигнута: критерий останова опустился ниже `tolerance`. */
    var converged = false
        private set

    /**
     * Распознана расходимость: счёт прерван ДОСРОЧНО, предел итераций не исчерпан.
     * Отличать этот случай от «не хватило итераций» нужно в диагностике: иначе
     * сообщение утверждало бы, что перебраны все допустимые шаги, что неверно.
     */
    var diverged = false
        private set

    /** Число фактически выполненных итераций. */
    var performedIterations = 0
        private set

    /**
     * Последнее КОНЕЧНОЕ значение критерия останова — то, что уходит в
     * [numerics.SolutionFunc.residual].
     *
     * Именно конечное, а не просто последнее: при расходимости с переполнением
     * последним значением оказывается `Inf` или `NaN`, и такая «невязка» ничего
     * не сообщает о том, насколько плох результат.
     *
     * Начальное значение `NaN` заменяется на первом ЖЕ вызове [accept] с конечным
     * `diff`. Формально оно могло бы уцелеть, если бы `diff` оказался нечислом уже на
     * первой итерации — и тогда контракт `residual > 0 && !isNaN`, который проверяет
     * `DivergenceContractTest`, был бы нарушен. Этот случай НЕДОСТИЖИМ: первый итерант
     * есть `f` с конечными значениями, второй — его образ под оператором конечного
     * ранга с ограниченным ядром, поэтому разность на первом шаге конечна при любом
     * `cL`. Переполнение — результат НАКОПЛЕННОГО геометрического роста и требует
     * десятков шагов, к которым поле уже заполнено (и к которым счёт обычно уже
     * прерван распознаванием роста).
     */
    var residual = Double.NaN
        private set

    /**
     * Наименьшее достигнутое значение критерия — база для распознавания роста.
     * Сравнение ведётся с минимумом, а не с предыдущим шагом: при геометрической
     * расходимости отношение соседних значений равно знаменателю прогрессии и
     * ограничено, поэтому пошаговое сравнение не сработало бы никогда, тогда как
     * накопленный рост относительно минимума растёт неограниченно (подробное
     * обоснование — в KDoc [DIVERGENCE_GROWTH_FACTOR]).
     */
    private var minDiff = Double.POSITIVE_INFINITY

    /**
     * Принять очередное значение критерия останова и решить, прерывать ли цикл.
     *
     * @param diff равномерная норма разности соседних итерантов на контрольных точках.
     * @return `true`, если цикл следует прервать (по сходимости либо по расходимости).
     */
    fun accept(diff: Double): Boolean {
        performedIterations++
        if (diff.isFinite()) residual = diff
        // Сходимость проверяется ПЕРВОЙ (см. KDoc класса). Сравнение `NaN < tolerance`
        // даёт `false`, поэтому нечисло сюда не проскочит.
        if (diff < tolerance) {
            converged = true
            return true
        }
        if (!diff.isFinite() || (minDiff.isFinite() && diff > DIVERGENCE_GROWTH_FACTOR * minDiff)) {
            diverged = true
            return true
        }
        // На первом шаге `minDiff` равен `+Inf` (не конечен), поэтому расходимость
        // не может быть объявлена раньше, чем накоплена база для сравнения.
        if (diff < minDiff) minDiff = diff
        return false
    }
}
