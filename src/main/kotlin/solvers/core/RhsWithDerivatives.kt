package solvers.core

/**
 * Правая часть `f` уравнения вместе с двумя своими производными.
 *
 * Тройка `f`, `f'`, `f''` НИКОГДА не путешествует порознь: семейства функционалов
 * `chi_j` принимают ровно её (`ApproxFunctional.apply(f, fD, fDD)`), причём какие
 * именно производные будут прочитаны, решает СЕМЕЙСТВО, а не решатель — `theta`
 * не читает ни одной, `xi` читает первую, `xi^<0>` — обе. Поэтому передавать их
 * тремя независимыми параметрами значило бы разрешить состояние, которого не
 * существует: производная от ОДНОЙ функции рядом со значением ДРУГОЙ. Такая
 * рассинхронизация не диагностируется никак — она просто даёт неверную систему
 * (ровно этот дефект уже случался с `f''`, которую забывали пробросить, и семейство
 * `xi^<0>` молча получало ноль).
 *
 * ### Почему обычный класс, а не `data class`
 *
 * Поля — лямбды, у которых `equals` — сравнение по ссылке, поэтому автоматические
 * `equals`/`hashCode` не несли бы смысла, а `toString` печатал бы имена
 * синтетических классов. Ни один из этих членов не нужен.
 *
 * ### Горячий путь
 *
 * Объект создаётся ОДИН РАЗ на решатель, а [SecondKindSolverCore] сразу распаковывает
 * его в три собственных поля. Поэтому в циклах сборки матриц и в итерациях остаётся
 * то же одно разыменование поля с последующим `invoke`, что и раньше: ни аллокаций,
 * ни лишнего уровня косвенности не добавляется.
 *
 * @param value сама правая часть `f(t)`.
 * @param deriv первая производная `f'(t)`.
 * @param deriv2 вторая производная `f''(t)`. Значение по умолчанию `{ 0.0 }`
 *        сохранено с прежней сигнатуры: его используют вызывающие, работающие с
 *        семействами, которым вторая производная не нужна.
 */
class RhsWithDerivatives(
    val value: (Double) -> Double,
    val deriv: (Double) -> Double,
    val deriv2: (Double) -> Double = { 0.0 },
)
