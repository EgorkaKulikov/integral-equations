package solvers.uryson

import numerics.LinearAlgebra

/**
 * Итог прогона ньютоновских итераций: сколько шагов ФАКТИЧЕСКИ выполнено, какова
 * невязка и по какой причине счёт прекращён.
 *
 * @param converged признак достижения сходимости. Выставляется ТОЛЬКО тогда, когда
 *        норма невязки в возвращаемой точке фактически ниже допуска, — независимо
 *        от того, какой критерий прервал цикл (см. [runNewtonIterations]).
 * @param performedSteps число ФАКТИЧЕСКИ выполненных шагов Ньютона. Ноль означает,
 *        что начальное приближение уже удовлетворяло критерию по невязке и вектор
 *        неизвестных не изменялся.
 * @param stalled счёт прерван ЗАСТОЕМ: норма шага стала пренебрежимо мала, а невязка
 *        осталась выше допуска. Предел шагов при этом НЕ исчерпан, поэтому его
 *        повышение бессмысленно — процесс уже не двигается. Отличать этот случай
 *        нужно в диагностике: сообщение «не хватило итераций» здесь вводило бы
 *        в заблуждение. Возможен только при `converged == false`.
 * @param residual норма невязки. ПРИ `converged == true` — всегда в ТОЙ ЖЕ точке,
 *        которая возвращается наружу. ПРИ `stalled == true` — тоже в возвращаемой
 *        точке (пересчёт уже сделан, именно он и показал недостаточность). ПРИ
 *        исчерпании предела шагов (`converged == false && !stalled`) — невязка перед
 *        ПОСЛЕДНИМ шагом, а НЕ в возвращаемой точке; это СОЗНАТЕЛЬНО, обоснование —
 *        в [runNewtonIterations].
 */
internal class NewtonRun(
    val converged: Boolean,
    val performedSteps: Int,
    val stalled: Boolean,
    val residual: Double,
)

/**
 * ЕДИНЫЙ ЦИКЛ НЬЮТОНА для всех итерационных схем уравнения Урысона второго рода.
 *
 * Три схемы решателя ([UrysonSecondKindSolver.solveBase], `kulkarni`, `nystrom`)
 * строят РАЗНЫЕ системы `F(x) = 0` и решают шаг РАЗНЫМИ якобианами (аналитический
 * `I - lambda B(c)` в первых двух, конечно-разностный в третьей), но управляющая
 * логика у них была выписана трижды дословно — и трижды содержала одни и те же два
 * дефекта отчётности:
 *
 *  1. счётчик увеличивался ДО проверки невязки, поэтому при мгновенной сходимости
 *     наружу уходило `iterations = 1` при НУЛЕ выполненных шагов;
 *  2. при выходе по критерию шага вектор неизвестных уже был обновлён, а норма
 *     невязки оставалась посчитанной в ПРЕДЫДУЩЕЙ (худшей) точке — отчёт о качестве
 *     относился не к тому приближению, которое возвращается.
 *
 * Здесь логика существует В ЕДИНСТВЕННОМ экземпляре; схемы задают только `F` и шаг.
 * Так дефект не сможет воспроизвестись в четвёртой схеме — тот же приём, что уже
 * применён к простым итерациям ([solvers.core.IterationStopCriterion]).
 *
 * ДВА УСЛОВИЯ ВЫХОДА, и оба ведут к ОДНОЙ И ТОЙ ЖЕ проверке успеха.
 *  1. Невязка опустилась ниже допуска — успех по определению.
 *  2. Норма шага стала пренебрежимо мала. Это условие ЗАСТОЯ, а НЕ достижения
 *     точности: оно говорит лишь о том, что итерация перестала двигаться. Совпадать
 *     с успехом оно обязано не всегда — малый шаг при большой невязке штатно возникает
 *     на плохо обусловленном якобиане `I - lambda B(c)` и на ПРИБЛИЖЁННОМ
 *     конечно-разностном якобиане схемы `nystrom`. Поэтому после пересчёта невязки
 *     в новой точке она СРАВНИВАЕТСЯ с допуском, и `converged` выставляется по
 *     фактическому результату, а не безусловно. Прежний код объявлял успех в обоих
 *     случаях: флаг `converged` мог утверждать сходимость при невязке ВЫШЕ
 *     затребованной, то есть был недостоверен ровно там, где он и нужен.
 *
 * ПОРЯДОК ОПЕРАЦИЙ СОХРАНЁН БИТ-В-БИТ по отношению к прежним трём циклам:
 *  - число выполненных шагов при исчерпании предела по-прежнему равно `maxSteps`
 *    (условие `performedSteps < maxSteps` проверяется до шага, как и раньше);
 *  - проверка невязки по-прежнему предшествует шагу, поэтому точка выхода по
 *    невязке та же;
 *  - точки выхода по шагу те же: сравнение с допуском НЕ продолжает цикл, а лишь
 *    определяет значение флага, поэтому возвращаемый вектор `x` не меняется;
 *  - пересчёт невязки при выходе по шагу выполняется ТЕМ ЖЕ [residualAt], что и
 *    основной расчёт: вторая формула невязки не появляется.
 * Единственное вычислительное отличие — один ДОПОЛНИТЕЛЬНЫЙ вызов [residualAt] при
 * выходе по критерию шага. Он не меняет вектор неизвестных, то есть решение
 * остаётся тем же; меняется только сообщаемое о нём число.
 *
 * ПРИ ИСЧЕРПАНИИ ПРЕДЕЛА невязка ЗАНОВО НЕ МЕРИТСЯ, и это не недоработка.
 * В этой ветви процесс не сошёлся, поэтому последний шаг мог увести точку
 * сколь угодно далеко, и пересчёт мог бы превратить КОНЕЧНОЕ диагностическое
 * значение в `Inf`/`NaN` — то есть УХУДШИТЬ диагностику расходимости ровно там,
 * где она нужна больше всего (тот же довод, что у поля
 * [solvers.core.IterationStopCriterion.residual]: важно КОНЕЧНОЕ значение).
 * Дефект, исправляемый здесь, касался именно СОШЕДШЕГОСЯ результата: там число
 * трактуется как оценка качества ответа и обязано относиться к самому ответу.
 *
 * @param x вектор неизвестных; ИЗМЕНЯЕТСЯ НА МЕСТЕ и после возврата содержит
 *        найденное приближение.
 * @param maxSteps предел числа шагов Ньютона.
 * @param tolerance требуемая величина критерия останова (общая для невязки и шага).
 * @param residualAt невязка `F(x)` в текущей точке. Вызывается один раз на итерацию
 *        (плюс один раз при выходе по критерию шага).
 * @param stepAt шаг Ньютона `delta = -J^{-1} F(x)` по текущей точке и невязке в ней.
 *        Невязка передаётся аргументом, а не вычисляется повторно: у схемы Nyström
 *        она стоит `p` вычислений правой части.
 *
 *        ГАРАНТИЯ ПОРЯДКА ВЫЗОВОВ, НА КОТОРУЮ МОЖНО ОПИРАТЬСЯ: каждому вызову
 *        `stepAt` непосредственно предшествует вызов [residualAt] В ТОЙ ЖЕ ТОЧКЕ,
 *        без каких-либо вызовов между ними. Это часть контракта, а не деталь
 *        реализации: `nystrom` переносит через неё промежуточное `G(x)` из расчёта
 *        невязки в расчёт якобиана, чтобы не считать правую часть дважды.
 *        Перестановка или пропуск вызова сломает эту передачу, поэтому менять
 *        порядок нельзя (нарушение поймает `error` на стороне `nystrom`).
 */
internal fun runNewtonIterations(
    x: DoubleArray,
    maxSteps: Int,
    tolerance: Double,
    residualAt: (DoubleArray) -> DoubleArray,
    stepAt: (DoubleArray, DoubleArray) -> DoubleArray,
): NewtonRun {
    var performedSteps = 0
    var converged = false
    var stalled = false
    var lastResidual = Double.NaN
    while (performedSteps < maxSteps) {
        val f = residualAt(x)
        lastResidual = LinearAlgebra.normInf(f)
        // Сравнение с `NaN` даёт `false`, поэтому нечисло сходимостью не считается.
        if (lastResidual < tolerance) {
            converged = true
            break
        }
        val delta = stepAt(x, f)
        for (i in x.indices) x[i] += delta[i]
        // Счётчик увеличивается ПОСЛЕ фактического шага: `performedSteps` означает
        // число выполненных шагов, а не число проверок критерия.
        performedSteps++
        if (LinearAlgebra.normInf(delta) < tolerance) {
            // Точка уже сдвинута строкой выше, поэтому невязку надо мерить ЗАНОВО:
            // прежнее значение относилось к точке ДО шага и систематически завышало
            // погрешность возвращаемого ответа. Замер расхождения: базовая схема,
            // задача B, `tol = 1e-10`, n=8 — сообщалось `2.74e-10` вместо фактического
            // `4.44e-15`, то есть в 6.2e4 раз хуже действительного.
            lastResidual = LinearAlgebra.normInf(residualAt(x))
            // Малый шаг сам по себе успехом НЕ является (см. KDoc): решает невязка.
            converged = lastResidual < tolerance
            stalled = !converged
            break
        }
    }
    return NewtonRun(converged, performedSteps, stalled, lastResidual)
}
